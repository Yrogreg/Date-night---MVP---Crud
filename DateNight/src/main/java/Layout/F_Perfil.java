    private void carregar() {
        // Obtém o usuário da sessão em vez de criar um novo
        User u = UserSession.getInstance().getCurrentUser();
        if (u == null) {
            System.out.println("Nenhum usuário logado!");
            return;
        }

        this.id = u.getId(); // Agora pega o ID correto

        String sql = "SELECT email, nome, senha FROM user WHERE id = ?";
        try (Connection conn = Conect.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql)) {

            stmt.setInt(1, id);
            ResultSet rs = stmt.executeQuery();

            if (rs.next()) {
                txt_email.setText(rs.getString("email"));
                txt_senha.setText(rs.getString("senha"));
                txt_nome.setText(rs.getString("nome"));
            } else {
                System.out.println("Usuário não encontrado no BD.");
            }
        } catch (SQLException e) {
            System.out.println("Erro SQL: " + e.getMessage());
        }
    }
