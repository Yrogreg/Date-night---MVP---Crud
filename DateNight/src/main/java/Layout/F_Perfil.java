    private void bt_editarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bt_editarActionPerformed
        try {  
            String email = txt_email.getText();
            String senha = txt_senha.getText();
            String nome = txt_nome.getText();

            if (nome.trim().isEmpty()) {
                mostrarMensagem("O nome não pode estar vazio!");
                return;
            }

            if (!isEmailValido(email)) {
                mostrarMensagem("Email inválido!");
                return;
            }
            
            // Registra user
            Edit e = new Edit();
            e.EditUser(this.id,nome,email, senha);
            
            // fecha janela
            mostrarMensagem("Edição Salva!");

        } catch (Exception e) {
            System.out.println("Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_bt_editarActionPerformed

    private boolean isEmailValido(String email) {
        return email.matches("^[\\w-\\.]+@([\\w-]+\\.)+[\\w-]{2,4}$");
    }

    private boolean isSenhaValida(String senha, String senhaConfirm) {
        if (senha.length() < 6 || senhaConfirm.length() < 6) {
            mostrarMensagem("A senha deve ter no minimo 6 caracteres!");
            return false;
        }
        if (!senha.equals(senhaConfirm)) {
            mostrarMensagem("As senhas não coincidem!");
            return false;
        }
        return true;
    }

    private int isCertificacaoValida(int certificacao) {
        if (certificacao == 3){
            return 0;
        }else{
            return 1;
        }
    }

    private void mostrarMensagem(String mensagem) {
        JOptionPane.showMessageDialog(null, mensagem);
    }
